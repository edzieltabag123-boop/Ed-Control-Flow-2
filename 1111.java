
public class NumberSquarePrinter {
    public static void main(String[] args) {

        // Print numbers from 1 to 10 and their squares
        for (int i = 1; i <= 10; i++) {
            System.out.println("Number: " + i + " | Square: " + (i * i));
        }

        // Change the loop limit to 20 to print numbers from 1 to 20.
    }
}
